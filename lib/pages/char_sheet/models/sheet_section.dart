/// Секции листа персонажа. На десктопе характеристики/навыки видны всегда как
/// колонки, а правая панель переключается между «правыми» секциями; на мобилке
/// все секции листаются через один переключатель.
enum SheetSection {
  abilities('Характеристики и навыки'),
  attacks('Атаки и умения'),
  features('Дополнительные способности'),
  equipment('Снаряжение и сокровища'),
  senses('Пассивные чувства и владения'),
  personality('Личность и внешность'),
  goals('Цели и задачи'),
  notes('Заметки'),
  spells('Заклинания');

  const SheetSection(this.label);

  final String label;
}
